"""Streamlit UI for AI SQL Reviewer. All API access lives in the sqlreviewer package."""

from pathlib import Path

import streamlit as st

from sqlreviewer import config
from sqlreviewer.errors import ValidationError
from sqlreviewer.service import review
from ui import render

ROOT = Path(__file__).parent
EXAMPLES_DIR = ROOT / "examples"

st.set_page_config(page_title="AI SQL Reviewer", layout="wide")


@st.cache_data
def load_examples() -> dict[str, str]:
    return {p.stem.replace("_", " ").strip(): p.read_text(encoding="utf-8")
            for p in sorted(EXAMPLES_DIR.glob("*.sql"))}


@st.cache_data
def load_css() -> str:
    return (ROOT / "ui" / "style.css").read_text(encoding="utf-8")


def _load_example():
    choice = st.session_state.get("example_choice")
    if choice in EXAMPLES:
        st.session_state["sql_input"] = EXAMPLES[choice]


def html(fragment: str):
    st.markdown(fragment, unsafe_allow_html=True)


EXAMPLES = load_examples()
html(f"<style>{load_css()}</style>")

html('<h1 class="title">Review your SQL before it ships</h1>')
html('<p class="lede">Paste a query. Local checks and an AI reviewer flag risks, '
     'with the reasoning and a suggested rewrite.</p>')
html('<div class="disclaimer"><b>AI recommendations require human review.</b> '
     'Suggestions can be wrong, incomplete, or not actually faster, so test any change '
     'against your own data and execution plans. Your SQL is analysed as text and '
     'is <b>never executed</b>.</div>')

left, right = st.columns([3, 1], gap="large")
with right:
    dialect = st.selectbox("SQL dialect", config.DIALECTS)
    st.selectbox("Load an example", [""] + list(EXAMPLES), key="example_choice",
                 on_change=_load_example, format_func=lambda x: x or "None")
with left:
    sql = st.text_area("SQL to review", key="sql_input", height=300,
                       placeholder="Paste a query here…")
    st.caption(f"{len(sql):,} of {config.MAX_SQL_CHARS:,} characters. "
               "The text is sent to OpenAI, so leave out credentials and sensitive data.")
    clicked = st.button("Review SQL", type="primary")

if clicked:
    try:
        with st.spinner("Reviewing…"):
            result = review(sql, dialect)
    except ValidationError as exc:
        st.error(exc.user_message)
    else:
        ai = result["ai"]
        note = ("The higher of the local heuristic risk and the AI-assessed risk."
                if ai else "AI review unavailable, so this reflects the local heuristic checks only.")
        html(render.risk_block(result["overall_risk"], note))

        html(render.section_head(
            "Heuristic checks",
            "Deterministic text-pattern rules that run locally. Conservative hints with no "
            "knowledge of your schema, indexes or data.", "heuristic"))
        html(render.findings_html(result["heuristic_findings"], "No heuristic patterns matched."))

        html(render.section_head(
            "AI review", "Generated by an AI model, and may contain mistakes.", "ai"))
        if result["ai_error"]:
            st.error(result["ai_error"])
        else:
            from html import escape
            html(f'<p class="ai-summary">{escape(ai["summary"])}</p>')
            html(render.findings_html(ai["findings"], "The AI reported no findings."))

            html(render.section_head(
                "Suggested rewrite", "AI-generated and unverified. Not guaranteed to be "
                "equivalent to the original or faster.", "ai"))
            st.code(ai["suggested_sql"], language="sql")

            if ai["caveats"]:
                html(render.section_head("Caveats", "What the reviewer could not know.", "ai"))
                html(render.caveats_html(ai["caveats"]))
